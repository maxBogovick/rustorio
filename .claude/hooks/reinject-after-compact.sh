#!/bin/bash
# SessionStart(compact): после сжатия контекста вернуть в него то, без чего агент начинает
# «выглядит готовым» вместо «проверено».
#
# Сжатие пересказывает разговор и может потерять именно операционные детали — какой гейт,
# какой порог, кто коммитит. Проектный CLAUDE.md после компакта перечитывается сам, а вот
# состояние текущей работы — нет. Всё, что этот скрипт печатает в stdout, добавляется в контекст.
set -uo pipefail

cd "$CLAUDE_PROJECT_DIR" 2>/dev/null || exit 0

changed=$(git status --porcelain 2>/dev/null | head -20)

cat <<TXT
[после сжатия контекста — рабочие условия этой сессии]
Гейт: ./gradlew build (компиляция + NullAway + все тесты + jacoco; src/tools и src/editor входят).
Бенчмарк: ./gradlew benchmark — порог зашит в самой команде, красный прогон = правка не принята.
Правка поведения закрывается тестом, падавшим на старом коде. «Проверено визуально» — не доказательство.
Окно игры в headless-сессии не запускается: что не проверено, называть прямо.
Коммит и пуш делает владелец, без явной просьбы не коммитить.
TXT

if [ -n "$changed" ]; then
  printf 'Незакоммиченные изменения на момент сжатия:\n%s\n' "$changed"
fi
exit 0
