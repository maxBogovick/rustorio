package com.petrochem;

/**
 * Сколько пластика произведено за сессию — то, что делает подписку на событие видимой: крекер
 * показывает это число в панели осмотра, иначе счётчик был бы кодом, который никто не читает.
 *
 * <p>Именно за сессию, а не за мир: шина событий одна на загрузку игры, а не на мир, поэтому счёт
 * не сбрасывается при старте новой игры. Это ограничение шины, а не недосмотр — величина,
 * привязанная к конкретному миру, регистрируется сервисом ({@code registerService} вызывает
 * провайдер один раз на каждый мир), а не считается на событиях.
 *
 * <p>Обычный объект, а не статическое поле: экземпляр создаёт точка входа мода и раздаёт его своим
 * зданиям через фабрику прототипа. Статический счётчик пережил бы и мод, и мир, и тест.
 */
final class PlasticCounter {

    private long produced;

    void increment() {
        produced++;
    }

    long produced() {
        return produced;
    }
}
