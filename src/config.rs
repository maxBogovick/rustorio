//! config.rs — ВСЕ настройки игры в одном месте.
//!
//! Золотое правило: если хочешь «покрутить число» — оно живёт здесь и только здесь.
//! Это самый нижний слой архитектуры: от него можно зависеть, он не зависит ни от кого.

// ── Размер поля (в клетках) ──────────────────────────────────────────
pub const GRID_W: i32 = 34;
pub const GRID_H: i32 = 20;

// ── Геометрия экрана (в пикселях) ────────────────────────────────────
pub const TILE: f32 = 34.0; // сторона клетки
pub const OFFSET_X: f32 = 20.0; // отступ поля слева
pub const OFFSET_Y: f32 = 70.0; // отступ поля сверху (под панелью)
                                // Размер окна НЕ храним отдельно: он вычисляется из сетки в `main.rs`
                                // (`window_conf`). Иначе окно и поле — две независимые константы, которые
                                // легко рассогласовать; бумпнешь GRID_W — поле уедет за край окна.

// ── Время симуляции ──────────────────────────────────────────────────
/// Секунд на один шаг симуляции (тик). Меньше — быстрее «мир тикает».
pub const TICK: f32 = 0.18;
/// Потолок «наигранного» времени за кадр (защита от «спирали смерти»:
/// после долгого зависания не пытаемся отработать десятки тиков разом).
/// Классическое значение ~0.25с — см. Gaffer «Fix Your Timestep».
pub const MAX_FRAME_TIME: f32 = 0.25;

// ── Баланс зданий ────────────────────────────────────────────────────
/// Секунд на добычу одной руды буром.
pub const MINER_TIME: f32 = 0.9;
/// Секунд на плавку руды в пластину.
pub const SMELT_TIME: f32 = 1.2;
