package com.rustorio;

/**
 * Внешность здания — короткое описание того, что нарисовать: какой {@link Sprite} и, по желанию,
 * число-бейдж поверх (у ящика — сколько лежит, у топящейся печи — сколько руды в очереди).
 *
 * <p>Ключевая мысль: описание живёт в ДОМЕНЕ и не тянет за собой графику. Здание само решает, как
 * оно выглядит СЕЙЧАС (печь горячая или холодная — по своему буферу), и отдаёт это решение
 * готовым. Графике остаётся тупая, одинаковая для всех работа: взять спрайт по имени и, если есть
 * бейдж, подписать число. Никакого разбора «а это бур или ящик» в отрисовке больше нет.
 */
public record Appearance(Sprite sprite, int badge) {

    /** Значение бейджа «числа нет» — рисуем только спрайт. */
    public static final int NO_BADGE = -1;

    /** Внешность без числа-бейджа. */
    public static Appearance of(Sprite sprite) {
        return new Appearance(sprite, NO_BADGE);
    }

    /** Внешность с числом-бейджем поверх спрайта. */
    public static Appearance of(Sprite sprite, int badge) {
        return new Appearance(sprite, badge);
    }

    /** Есть ли что подписывать поверх спрайта. */
    public boolean hasBadge() {
        return badge != NO_BADGE;
    }
}
