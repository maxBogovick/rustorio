package com.rustorio;

/**
 * Здание на карте — общий тип для всего, что мир держит в клетках и «проживает» каждый тик.
 *
 * <p>До этого урока бур и ящик были двумя несвязанными классами, а мир вёл под них две
 * отдельные карты, две пары {@code has/place} и два цикла отрисовки. Дублирование созрело —
 * извлекаем то, что у зданий ОБЩЕЕ: мир хочет держать здание в клетке и раз в тик давать ему
 * прожить шаг, не зная, бур это или ящик.
 *
 * <p><b>Почему {@code sealed}.</b> Список зданий закрыт — {@link Miner}, {@link Chest},
 * {@link Furnace}, {@link Belt}, {@link Splitter} и {@link SpeedModule}: посторонний класс не
 * может втихую стать зданием. Взамен компилятор дарит проверку полноты — раньше это означало,
 * что {@code switch} по зданию в отрисовке обязан разобрать все сорта; с урока 8 такого switch
 * в отрисовке уже нет (она спрашивает {@link #appearance()} у всех одинаково), так что польза
 * теперь в другом: сам список — гарантия, что зданием нельзя стать тайком, в обход этого файла.
 *
 * <p><b>Налог за {@code sealed}, который SpeedModule платит честно (урок 17).</b> Decorator по
 * своей природе хочет ОБОРАЧИВАТЬ любой объект интерфейса, не спрашивая разрешения у автора
 * интерфейса. {@code sealed} — противоположная идея: список оборачиваемых типов закрыт и должен
 * знать о декораторе заранее. {@link SpeedModule} обязан быть явно вписан сюда, а не просто
 * реализовать {@code Building} где угодно — это и есть трение между двумя идеями, не досадная
 * мелочь.
 */
public sealed interface Building
        permits Miner, Chest, Furnace, Belt, Splitter, SpeedModule, Lab, UndergroundBelt {

    /**
     * Прожить один тик — один шаг игрового времени. Мир зовёт этот метод у каждого здания раз
     * в кадр.
     *
     * <p>Зачем зданию передают его собственные координаты? Само здание их не хранит — их знает
     * только мир (здание лежит в карте «клетка → здание», ключ и есть координата). Но чтобы
     * что-то сделать с СОСЕДЯМИ, зданию надо знать, где оно само стоит: бур из клетки
     * {@code (x, y)} ищет ящик в клетке {@code (x+1, y)} и т.п. Поэтому мир и передаёт
     * координаты снаружи, а не хранит их дважды.
     *
     * <p>По умолчанию — ничего: большинство зданий (ящик) просто стоит. Кто активен (бур) —
     * переопределяет.
     *
     * @param world мир, через который здание видит соседей и передаёт им предметы
     * @param x     столбец клетки, в которой стоит это здание (0 — левый край поля)
     * @param y     строка клетки, в которой стоит это здание (0 — верхняя строка поля)
     */
    default void tick(World world, int x, int y) {
    }

    /**
     * Принять предмет от соседа.
     *
     * <p>Это второй «глагол» общего словаря, которым мир говорит со зданиями (первый — {@link
     * #tick}). Раньше мир сам перебирал через {@code instanceof}, кто умеет принимать; теперь он
     * просто спрашивает у здания — а здание само за себя отвечает.
     *
     * <p>По умолчанию — НЕ принимает (бур только отдаёт руду, ничего не берёт). Кто принимает
     * (ящик, печь) — переопределяет. Тот же приём «пустая реализация по умолчанию», что и у
     * {@code tick}: здание опционально включается в те взаимодействия, которые ему нужны.
     *
     * <p>{@code world} передаётся и сюда (не только в {@code tick}) — печи нужен доступ к {@link
     * Research}, чтобы узнать вместимость буфера с учётом технологии {@link Tech#BIG_BUFFER}
     * прямо в момент решения «принять или нет».
     *
     * @param world мир — источник открытых технологий и прочего общего состояния
     * @param item предлагаемый предмет
     * @return {@code true}, если предмет принят; {@code false}, если это здание его не берёт
     *         (тогда предлагающий оставит предмет себе или отдаст другому соседу)
     */
    default boolean accept(World world, Item item) {
        return false;
    }

    /**
     * Какой предмет здание сейчас физически держит «в пути» — то, что рисуется поверх тайла как
     * груз (лента, сортировщик, бур с несданной рудой, подземка). По умолчанию — ничего: у ящика,
     * печи и лаборатории свой предмет — это буфер ВНУТРИ здания, он уже показан числом-бейджем в
     * {@link #appearance()}, второй раз рисовать его как груз незачем.
     */
    default Item heldItem() {
        return null;
    }

    /**
     * В сколько слоёв {@link SpeedModule} обёрнуто это здание — {@code 0}, если не обёрнуто вовсе.
     *
     * <p>Нужно ИСКЛЮЧИТЕЛЬНО {@link SaveGame}: {@code type()} и {@code save()} у обёрнутого
     * здания делегируют к тому, что внутри (см. {@link SpeedModule}) — так и задумано для тика
     * и отрисовки, но из файла сохранения тогда пропадала бы САМА обёртка, а вместе с ней и
     * апгрейд (печь после F5→F9 незаметно становилась вдвое медленнее). Обёртка — единственное
     * состояние здания, которое не может рассказать о себе через {@code save()}, поэтому у него
     * отдельный, узкоспециальный метод.
     */
    default int speedLevel() {
        return 0;
    }

    /**
     * Как здание выглядит ПРЯМО СЕЙЧАС — спрайт и, по желанию, число-бейдж.
     *
     * <p>В отличие от {@code tick}/{@code accept}, у этого метода НЕТ реализации по умолчанию:
     * у любого здания есть внешность, значит каждое обязано её описать. Это и держит отрисовку
     * простой — она не разбирает сорта зданий, а просто спрашивает у каждого его {@link
     * Appearance}. Добавишь новое здание — компилятор потребует реализовать и этот метод.
     */
    Appearance appearance();

    /**
     * Какого я сорта — та же метка, что в панели постройки ({@link BuildingType}).
     *
     * <p>Нужно сохранению (урок 10): чтобы записать здание в файл и потом узнать по файлу, какой
     * класс воссоздавать, нужен тег сорта. Мог бы разбираться `instanceof`-цепочкой в
     * {@code SaveGame} — но это та самая болезнь из урока 6. Пусть здание назовёт себя само.
     */
    BuildingType type();

    /**
     * Собственное состояние в виде текста — всё, что нужно, чтобы потом воссоздать ЭТО ЖЕ здание,
     * а не здание с нуля. У бура это `cooldown`, у ящика — `count`, у печи — буфер и таймер сразу.
     * Формат строки решает сам класс; {@code SaveGame} его не разбирает, только записывает как
     * есть в файл рядом с координатами.
     */
    String save();

    /**
     * Правда ли, что этому зданию всё равно, в каком порядке (относительно соседей) его тикают
     * за один шаг мира. По умолчанию — да: большинство зданий никуда прицельно не толкают предмет.
     *
     * <p>Лента (урок 19), толкающая ВЛЕВО или ВВЕРХ, — исключение: {@link World#tick()} обходит
     * здания от больших координат к меньшим, чтобы лента ВПРАВО/ВНИЗ не подтолкнула соседа, который
     * ещё не тикал в этом кадре (урок 11). Для ленты влево/вверх этот же порядок — ОБРАТНЫЙ
     * правильному, и она возвращает {@code false}, прося обход в другую сторону.
     */
    default boolean prefersDescendingTick() {
        return true;
    }
}
