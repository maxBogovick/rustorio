package com.rustorio;

/**
 * Сорт здания, который игрок может ВЫБРАТЬ в меню постройки.
 *
 * <p>Зачем этот enum, если в уроке 4 мы нарочно НЕ заводили «сорт здания» и обошлись
 * {@code sealed}-типами? Потому что задача другая. Там нужно было РАЗЛИЧАТЬ поведение готового
 * здания — это делает полиморфизм. Здесь нужен СПИСОК того, что можно построить: лёгкие ярлычки,
 * которые существуют БЕЗ самого здания — чтобы показать их в панели, выбрать один и по нему
 * поставить постройку. Для «меню выбора» естественная форма — перечисление.
 *
 * <p>Порядок констант = порядок в панели и номера клавиш (1, 2, 3…). Ярлык — латиницей: экранный
 * шрифт кириллицу не рисует.
 */
public enum BuildingType {
    MINER("Miner"),
    CHEST("Chest"),
    FURNACE("Furnace"),
    BELT("Belt"),
    SPLITTER("Splitter"),
    PRESS("Press");

    private final String label;

    BuildingType(String label) {
        this.label = label;
    }

    /** Подпись для панели постройки (ASCII — экранный текст только латиницей). */
    public String label() {
        return label;
    }
}
