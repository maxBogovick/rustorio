package com.rustorio;

/**
 * Предмет, который существует в игре.
 *
 * <p>Началось с одной руды; с приходом печи (урок 5) появился и продукт переплавки — железная
 * пластина. Ровно как обещали: перечисление растёт, когда появляется, ЧТО в него добавить.
 * Пустых «на будущее» вариантов не заводим — каждый элемент под конкретную нужду.
 *
 * <p>Вторая цепочка (бронза) — то же самое устройство, что и железная, просто с другой рудой:
 * {@link OreMap} решает, какая руда лежит под клеткой, а печь ({@link Furnace}) сама подбирает
 * рецепт под то, что ей принесли (см. {@link Recipe#find}).
 */
public enum Item {
    /** Сырьё: бур добывает его из руды на карте. */
    IRON_ORE,
    /** Продукт первой ступени: печь переплавляет руду в пластину. */
    IRON_PLATE,
    /** Продукт второй ступени: пресс превращает пластину в шестерёнку (урок 16). */
    GEAR,
    /** Сырьё второй цепочки — бронзовая руда. */
    BRONZE_ORE,
    /** Продукт первой ступени бронзовой цепочки. */
    BRONZE_PLATE,
    /** Продукт второй ступени бронзовой цепочки — питает лабораторию наравне с {@link #GEAR}. */
    MECHANISM,
    /**
     * Верхний предмет: сводит вместе ОБЕ цепочки — прессу нужны сразу {@link #GEAR} и
     * {@link #MECHANISM} с двух разных лент (первый настоящий рецепт с двумя входами, см.
     * {@link Recipe#ENGINE}).
     */
    ENGINE,
    /**
     * Вторая ступень сборки: мотор ({@link #ENGINE}) плюс ещё одна {@link #GEAR} — тот же приём
     * двух входов, что и у мотора, только теперь один из входов сам уже собран из другого рецепта
     * (см. {@link Recipe#CHASSIS}). Кормит {@link Lab} наравне с остальной готовой продукцией.
     */
    CHASSIS,
    /**
     * Сплав: {@link #IRON_PLATE} И {@link #BRONZE_PLATE} вместе, на обычной {@link Furnace}
     * (не прессе) — первый рецепт печи с ДВУМЯ входами, см. {@link Recipe#ALLOY}. Ещё
     * промежуточный предмет, как {@link #IRON_PLATE}/{@link #BRONZE_PLATE}, — {@link Lab} его не
     * принимает, ждёт своего рецепта-потребителя.
     */
    ALLOY_PLATE,
    /**
     * Потребитель {@link #ALLOY_PLATE}: пресс превращает сплав в шестерню того же уровня, что
     * {@link #GEAR}/{@link #MECHANISM}, но из более дорогого материала (см. {@link
     * Recipe#ALLOY_GEAR}) — и, в отличие от пластины, это уже готовая продукция: кормит
     * {@link Lab} наравне с остальными предметами верхнего уровня.
     */
    ALLOY_GEAR
}
