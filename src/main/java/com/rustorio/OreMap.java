package com.rustorio;

/**
 * Где в мире лежит руда — функция от координат клетки, а не массив.
 *
 * <p>Детерминированная: одна и та же клетка всегда даёт один и тот же ответ, в каком бы
 * порядке её ни спрашивали. Залежи — те же 12 круглых пятен, что были в исходной игре
 * (первые четыре — стартовая область в левом верхнем углу карты).
 *
 * <p>Это первый кусочек «мира», возвращённый в логику: графике он нужен, чтобы нарисовать
 * карту с рудными областями. Полноценный {@code World} (клетки, здания) отстроится позже.
 */
public final class OreMap {

    /** Круглые залежи: (центр_x, центр_y, радиус). */
    private static final int[][] PATCHES = {
            {6, 5, 3}, {9, 14, 3}, {25, 6, 4}, {28, 15, 3},
            {52, 10, 4}, {74, 20, 3}, {45, 34, 4}, {14, 44, 3},
            {60, 52, 4}, {84, 42, 3}, {33, 56, 3}, {88, 8, 3},
    };

    private OreMap() {
    }

    /** Есть ли под клеткой {@code (x, y)} залежь руды. */
    public static boolean hasOre(int x, int y) {
        for (int[] patch : PATCHES) {
            int dx = x - patch[0];
            int dy = y - patch[1];
            int r = patch[2];
            if (dx * dx + dy * dy <= r * r) {
                return true;
            }
        }
        return false;
    }
}
