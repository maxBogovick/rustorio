package com.rustorio;

/**
 * Действие игрока, овеществлённое в объект: умеет применить себя к миру и откатить назад.
 *
 * <p>Раньше ЛКМ и ПКМ напрямую звали {@code world.place}/{@code world.removeBuilding} — сделал и
 * забыл, отменить нечем. Теперь между вводом и миром встаёт объект-действие: он знает, ЧТО было
 * сделано, и потому знает, как это отменить. Дальше не имеет значения, откуда действие взялось —
 * от клика мышью, из будущего меню, из повтора (redo) — применяется и откатывается оно всегда
 * одинаково.
 */
public interface PlayerAction {

    /**
     * Применить действие к миру.
     *
     * @return {@code true}, если что-то реально изменилось — тогда действие стоит запомнить для
     *         отмены; {@code false} — если применить не удалось (например, клетка занята) и
     *         помнить нечего
     */
    boolean apply(World world);

    /** Откатить ровно то, что сделал {@link #apply}. Зовут, только если {@code apply} вернул true. */
    void undo(World world);
}
