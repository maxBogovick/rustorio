package com.rustorio;

/**
 * Слушатель события «где-то на карте произвели предмет».
 *
 * <p>Раньше {@link World} знал ровно ОДНОГО получателя этого события — {@link ProductionStats} —
 * и вызывал его по имени напрямую. Этот интерфейс разводит источник события и того, кто на него
 * реагирует: миру больше не нужно знать, СКОЛЬКО слушателей и КАКИЕ они — только то, что каждый
 * умеет ответить на вопрос «предмет произведён, вот какой».
 */
@FunctionalInterface
public interface ProductionListener {
    void onProduced(Item item);
}
