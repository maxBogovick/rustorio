package com.rustorio;

import java.util.EnumMap;
import java.util.Map;

/**
 * Сколько каждого предмета произведено с начала игры — итог всего завода, а не отдельного
 * здания.
 *
 * <p>Каждое здание могло бы вести счёт своей добычи само, как ящик считает {@code count}. Но
 * тогда снос здания стёр бы его историю вместе с ним, а нам нужен ОБЩИЙ итог, переживающий
 * отдельные постройки. Поэтому счётчик живёт в мире, а не в зданиях (см. {@link World#stats()}).
 *
 * <p>Карта {@code Item → количество} вместо отдельного поля на каждый сорт предмета — по той же
 * причине, по которой панель постройки в HUD строится из {@code BuildingType.values()}: появится
 * новый предмет в {@link Item}, счётчик заработает для него сам, без правки этого класса.
 */
public final class ProductionStats {

    private final Map<Item, Long> totals = new EnumMap<>(Item.class);

    /** Отметить, что где-то на карте произвели один предмет. */
    void record(Item item) {
        totals.merge(item, 1L, Long::sum);
    }

    /** Сколько всего произведено предметов данного сорта с начала игры. */
    public long total(Item item) {
        return totals.getOrDefault(item, 0L);
    }

    /**
     * Задать итог напрямую, а не прибавить единицу. Отдельный от {@link #record} глагол — тот
     * считает игровые события («ещё один добыт»), этот восстанавливает точное число из файла
     * сохранения. Пишет только {@code SaveGame}.
     */
    void set(Item item, long total) {
        totals.put(item, total);
    }

    /** Обнулить все итоги — готовит статистику к загрузке нового сохранения. */
    void clear() {
        totals.clear();
    }
}
