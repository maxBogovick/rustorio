package com.rustorio;

/**
 * Технология: сколько очков исследований она стоит и как называется в HUD.
 *
 * <p>Как {@link Recipe} для печи — открытый для расширения список ДАННЫХ: новая технология не
 * требует ни строчки в {@link Research} или {@link Lab}, только новую константу здесь. Порядок
 * объявления — порядок разблокировки: {@link Research#addPoints} открывает технологии по
 * возрастанию {@link #cost}, одну за другой, как только очков хватает.
 *
 * <p>Каждая технология — это ГЛОБАЛЬНЫЙ апгрейд (все печи разом), в отличие от
 * {@link SpeedModule}, который ускоряет ровно одно здание, — тот же контраст, что описан в его
 * javadoc, теперь наконец воплощён.
 */
public enum Tech {
    /** Бур копает вдвое быстрее — везде на карте. */
    FAST_MINING(8, "Fast mining"),
    /** Печь и пресс готовят вдвое быстрее — везде на карте. */
    FAST_SMELTING(20, "Fast smelting"),
    /** Буфер печи и пресса вдвое больше — можно копить вдвое дольше про запас. */
    BIG_BUFFER(35, "Big buffers"),
    /** Подземная лента достаёт вдвое дальше. */
    LONG_TUNNEL(55, "Long tunnels"),
    /** Лаборатория тратит предмет на очко вдвое быстрее — эффект накапливается сам на себя. */
    FAST_LAB(80, "Fast research");

    private final int cost;
    private final String label;

    Tech(int cost, String label) {
        this.cost = cost;
        this.label = label;
    }

    /** Сколько накопленных очков исследований нужно, чтобы технология открылась. */
    public int cost() {
        return cost;
    }

    /** Подпись для HUD. */
    public String label() {
        return label;
    }
}
