package com.rustorio.core;

/**
 * Все настройки игры в одном месте — единственный «слой констант».
 *
 * <p>Золотое правило: хочешь «покрутить число» — оно живёт здесь и только здесь.
 * Это самый нижний слой архитектуры: от него можно зависеть, он не зависит ни от кого.
 *
 * <p>Класс {@code final} и с приватным конструктором — его нельзя ни создать,
 * ни отнаследовать. Это идиома «utility class»: только статические константы.
 *
 * <p>По ходу курса сюда будут добавляться новые константы (баланс зданий, скорость
 * лент, время тика машин) — каждая появится в своей лекции, вместе с кодом,
 * которому она нужна.
 */
public final class Config {

    private Config() {
        // Экземпляры не нужны: это чистый набор констант.
    }

    // ── Размер поля (в клетках) ──────────────────────────────────────
    // Поле больше окна во много раз: мир смотрят через камеру (скролл + зум),
    // окно и мир — независимые величины.
    public static final int GRID_W = 96;
    public static final int GRID_H = 64;

    // ── Геометрия экрана (в пикселях) ────────────────────────────────
    /** Сторона одной клетки при зуме 1.0. */
    public static final float TILE = 34f;
    /** Ширина окна. НЕ вычисляется из сетки: мир смотрят через камеру. */
    public static final int WINDOW_W = 1280;
    /** Высота окна. */
    public static final int WINDOW_H = 800;

    // ── Камера ────────────────────────────────────────────────────────
    /** Скорость панорамирования клавишами, ЭКРАННЫХ пикселей в секунду. */
    public static final float CAMERA_PAN_SPEED = 700f;
    /** Ближний предел зума (меньше = крупнее клетки). */
    public static final float CAMERA_ZOOM_MIN = 0.4f;
    /** Дальний предел зума (больше = видно больше мира). */
    public static final float CAMERA_ZOOM_MAX = 3.5f;
    /** Во сколько раз меняется зум на один «щелчок» колеса. */
    public static final float CAMERA_ZOOM_STEP = 1.15f;

    // ── Время симуляции ──────────────────────────────────────────────
    /** Секунд на один шаг симуляции (тик). Меньше — быстрее «мир тикает». */
    public static final float TICK = 0.18f;
    /**
     * Потолок «наигранного» времени за кадр — защита от «спирали смерти»:
     * после долгого зависания не пытаемся отработать десятки тиков разом.
     * Классическое значение ~0.25с (см. Gaffer «Fix Your Timestep»).
     */
    public static final float MAX_FRAME_TIME = 0.25f;

    // ── Баланс зданий ────────────────────────────────────────────────
    /** Секунд на добычу одной руды буром. */
    public static final float MINER_TIME = 0.9f;
    /** Секунд на переплавку одной руды в пластину. */
    public static final float SMELT_TIME = 1.2f;

    // ── Транспортные линии ────────────────────────────────────────────
    /**
     * Сколько предметов вмещает ОДНА клетка ленты вдоль линии.
     *
     * <p>В L5 клетка была зданием с одним предметом. Теперь клетка — это
     * {@code SLOTS_PER_TILE} слотов внутри {@link com.rustorio.model.BeltSegment}:
     * очередь на клетке стала плотнее без единой правки протокола передачи.
     */
    public static final int SLOTS_PER_TILE = 2;
    /**
     * На сколько слотов линия продвигает предметы за один тик.
     *
     * <p>Ровно {@link #SLOTS_PER_TILE}: предмет проезжает ровно одну клетку за
     * тик — то же ощущение скорости, что было у ленты в L5, но теперь очередь
     * на клетке вмещает больше одного груза.
     */
    public static final int BELT_SLOTS_PER_TICK = 2;
}
