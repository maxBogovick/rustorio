package com.rustorio.core;

/**
 * Все настройки игры в одном месте — единственный «слой констант».
 *
 * <p>Золотое правило (перенесено из Rust-версии): хочешь «покрутить число» —
 * оно живёт здесь и только здесь. Это самый нижний слой архитектуры: от него
 * можно зависеть, он не зависит ни от кого.
 *
 * <p>Класс {@code final} и с приватным конструктором — его нельзя ни создать,
 * ни отнаследовать. Это идиома «utility class»: только статические константы.
 */
public final class Config {

    private Config() {
        // Экземпляры не нужны: это чистый набор констант.
    }

    // ── Размер поля (в клетках) ──────────────────────────────────────
    public static final int GRID_W = 34;
    public static final int GRID_H = 20;

    // ── Геометрия экрана (в пикселях) ────────────────────────────────
    /** Сторона одной клетки. */
    public static final float TILE = 34f;
    /** Отступ поля слева. */
    public static final float OFFSET_X = 20f;
    /** Отступ поля сверху (под верхней панелью HUD). */
    public static final float OFFSET_Y = 70f;

    // ── Время симуляции ──────────────────────────────────────────────
    /** Секунд на один шаг симуляции (тик). Меньше — быстрее «мир тикает». */
    public static final float TICK = 0.18f;
    /**
     * Потолок «наигранного» времени за кадр — защита от «спирали смерти»:
     * после долгого зависания не пытаемся отработать десятки тиков разом.
     * Классическое значение ~0.25с (см. Gaffer «Fix Your Timestep»).
     */
    public static final float MAX_FRAME_TIME = 0.25f;

    // ── Баланс зданий ────────────────────────────────────────────────
    /** Секунд на добычу одной руды буром. */
    public static final float MINER_TIME = 0.9f;
    /** Секунд на плавку руды в пластину. */
    public static final float SMELT_TIME = 1.2f;
    /** Секунд на сборку одной шестерёнки. */
    public static final float ASSEMBLE_TIME = 0.8f;

    // ── Производные размеры окна ──────────────────────────────────────
    // Размер окна НЕ храним как отдельные «магические» числа: он вычисляется
    // из сетки, иначе окно и поле — две независимые величины, которые легко
    // рассогласовать (увеличишь GRID_W — поле уедет за край окна).
    public static int windowWidth() {
        return (int) (GRID_W * TILE + 2 * OFFSET_X);
    }

    public static int windowHeight() {
        return (int) (GRID_H * TILE + OFFSET_Y + OFFSET_X);
    }
}
