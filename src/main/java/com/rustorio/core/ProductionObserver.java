package com.rustorio.core;

/**
 * Наблюдатель производства: получает уведомление, когда в мире произведён предмет.
 *
 * <p>Это «Наблюдатель» (шаблон Observer). Источник события (машина) не знает, кто и зачем
 * его слушает; слушатель не знает, какая машина произвела предмет. Их связывает {@link
 * ProductionBus}. Благодаря этому счётчиков производства может быть сколько угодно, и ни
 * машина, ни другие слушатели об этом не знают.
 */
public interface ProductionObserver {

    /**
     * Произведено {@code amount} единиц предмета {@code item}.
     *
     * <p>Вызывается в фазе симуляции, поэтому обязан быть детерминированным и быстрым:
     * никаких «настенных часов» и тяжёлой работы (это же стережёт {@code ArchitectureTest}).
     */
    void onProduced(Item item, int amount);
}
