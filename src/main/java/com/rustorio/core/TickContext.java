package com.rustorio.core;

/**
 * Всё, что зданию нужно знать про текущий шаг симуляции.
 *
 * <p><b>Зачем «коробка» вместо обычных параметров.</b> Раньше метод здания выглядел
 * так: {@code update(float dt, boolean hasOre)} — причём {@code hasOre} нужен ТОЛЬКО
 * буру, но принимать его были обязаны все, включая ящик. Стоило зданиям понадобиться
 * что-то ещё (баланс, номер тика) — и сигнатуру пришлось бы править во всех зданиях
 * сразу. С коробкой сигнатура не меняется НИКОГДА: нужно новое — добавляется поле сюда.
 *
 * <p><b>Один объект на тик, а не на здание.</b> Все поля одинаковы для всех зданий в
 * пределах шага, поэтому {@code GameState} создаёт контекст один раз за тик. Если бы
 * сюда попал {@code hasOre} (свой у каждого бура), пришлось бы создавать объект на
 * каждое здание на каждом тике — мусор на ровном месте. Вместо этого бур узнаёт про
 * руду ОДИН раз, при постройке.
 */
public record TickContext(float dt, Balance balance) {
}
