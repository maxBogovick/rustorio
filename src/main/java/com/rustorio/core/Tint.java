package com.rustorio.core;

/**
 * Смысловой цвет подсветки — «что это значит», а не «какой RGBA».
 *
 * <p>Домен и {@code game} называют СМЫСЛ (выбрано, радиус, ошибка), а слой {@code render}
 * переводит его в конкретный цвет ({@code Palette.tint}). Благодаря этому логика может
 * попросить подсветку, не зная и не завися от палитры движка — тот же приём, что и с
 * {@link Appearance}.
 */
public enum Tint {
    /** Нейтральная пометка. */
    NEUTRAL,
    /** Хорошо/готово (зелёный). */
    GOOD,
    /** Предупреждение (жёлтый). */
    WARN,
    /** Ошибка/проблема (красный). */
    BAD,
    /** Выделение/наведение (белый). */
    SELECT,
    /** Зона действия/охват (синий). */
    RANGE,
    /** Полупрозрачный «призрак» будущего действия. */
    GHOST
}
