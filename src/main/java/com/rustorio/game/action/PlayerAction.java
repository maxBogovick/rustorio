package com.rustorio.game.action;

import com.rustorio.model.World;

/**
 * Действие игрока над миром как ОБЪЕКТ, а не прямой вызов — паттерн <b>Command</b>
 * (Nystrom, «Game Programming Patterns», глава Command).
 *
 * <p><b>Зачем овеществлять действие.</b> Раньше слой ввода прямо дёргал
 * {@code world.place(...)} — намерение игрока и мутация мира были сцеплены в одной
 * строке. Овеществив «поставить»/«снести» в объект с методами {@link #apply}/{@link
 * #revert}, мы получаем сразу три вещи, которых прямой вызов дать не может:
 * <ol>
 *   <li><b>Отмена/повтор.</b> Раз действие умеет само себя откатывать, история —
 *       это просто стек уже выполненных действий (см. {@code ActionHistory}).</li>
 *   <li><b>Переиспользование.</b> «Снести область» и «вставить чертёж» — это те же
 *       команды, собранные в {@link CompositeAction}; писать логику заново не нужно.</li>
 *   <li><b>Тестируемость.</b> Команда живёт в домене и не знает про libGDX: её можно
 *       выполнить и откатить в юнит-тесте без единого пикселя.</li>
 * </ol>
 *
 * <p><b>Честная граница отмены.</b> Команда откатывает СТРУКТУРУ (какое здание на
 * клетке), но НЕ состояние симуляции: мир детерминирован и едет вперёд, а предметы,
 * ехавшие по снесённой ленте, отменой не воскрешаются. Это осознанное сужение — так
 * ведут себя редакторы схем; «откат времени» — это уже replay, другой механизм.
 *
 * <p><b>sealed.</b> Набор видов действий закрыт ({@code permits}) — как и {@code
 * Building}: компилятор проследит, что каждый новый вид умеет и применяться, и
 * откатываться, и сообщать об эффекте. Забыть нельзя.
 */
public sealed interface PlayerAction
        permits PlaceBuilding, RemoveBuilding, CompositeAction {

    /**
     * Выполнить действие над миром. Здесь же команда ЗАПОМИНАЕТ, что было на клетке до
     * неё (мини-Memento), — без этого не откатиться. Можно вызывать повторно (это и есть
     * «повтор»/redo): каждый вызов заново снимает актуальный снимок.
     */
    void apply(World world);

    /** Откатить последствия последнего {@link #apply} — вернуть мир как было. */
    void revert(World world);

    /**
     * Изменил ли последний {@link #apply} мир на самом деле?
     *
     * <p>Часть контракта команды, а не деталь: протаскивание ленты по уже занятым
     * клеткам порождает «пустые» команды (guard мира их отклоняет). Слой ввода
     * спрашивает {@code hadEffect()}, чтобы не копить их в истории и не тратить впустую
     * шаг отмены.
     */
    boolean hadEffect();
}
