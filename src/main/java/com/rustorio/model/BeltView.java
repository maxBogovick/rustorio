package com.rustorio.model;

import java.util.List;

/**
 * Что отрисовке нужно знать о предметах на ленте — и ничего больше.
 *
 * <p>Это ДОГОВОР между лентами и рендером. Благодаря ему рендер плавного движения
 * можно писать, ничего не зная о том, как ленты устроены внутри: сегодня за этим
 * интерфейсом стоит транспортная линия, завтра — что угодно ещё.
 *
 * @see BeltSegment
 */
public interface BeltView {

    /**
     * Позиции предметов для кадра.
     *
     * @param alpha доля прожитого тика (0..1). Симуляция шагает раз в
     *              {@link com.rustorio.core.Config#TICK}, а кадров между тиками
     *              много: {@code alpha} говорит, насколько предмет уже уехал от
     *              своей прошлой позиции к текущей. Это и даёт плавность.
     */
    List<BeltItemPos> itemPositions(float alpha);
}
