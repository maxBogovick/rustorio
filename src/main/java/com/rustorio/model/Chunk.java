package com.rustorio.model;

/**
 * Кусок мира 32×32 клетки.
 *
 * <p><b>Зачем резать мир на куски.</b> Раньше мир был одним массивом, созданным при старте.
 * Массив нельзя дорастить: его размер фиксирован в момент создания. А нам нужен мир, который
 * растёт, и место под 50 000 зданий. Создать сразу гигантский массив тоже нельзя — память
 * уйдёт на пустоту, которой никто не пользуется.
 *
 * <p>Кусок создаётся, только когда в него впервые заглянули. Мир — словарь «координата куска
 * → кусок». Как блокнот, куда добавляешь страницу, только когда есть что на ней писать.
 *
 * <p><b>Почему 32×32,</b> а не 16 и не 64: это фактический стандарт (Factorio, Minecraft) —
 * компромисс между «слишком много мелких кусков» (накладные расходы на каждый) и «в куске
 * слишком много лишнего» (обходим впустую).
 *
 * <p>Класс пакетно-приватный: наружу устройство мира не торчит. В этом и смысл —
 * {@link World} остаётся фасадом, а всё остальное («сим», рендер, ввод) ходит по
 * координатам и вообще не знает, что мир поменял внутренности.
 */
final class Chunk {

    /** Сторона куска в клетках. */
    static final int SIZE = 32;
    /** Маска для остатка от деления на SIZE: {@code x & MASK} == {@code x % 32}, но быстрее. */
    static final int MASK = SIZE - 1;
    /** Сдвиг для деления на SIZE: {@code x >> SHIFT} == {@code x / 32}. */
    static final int SHIFT = 5;

    private final Tile[] tiles = new Tile[SIZE * SIZE];

    /**
     * @param chunkX координата куска (не клетки!)
     * @param chunkY координата куска
     */
    Chunk(int chunkX, int chunkY) {
        for (int ly = 0; ly < SIZE; ly++) {
            for (int lx = 0; lx < SIZE; lx++) {
                int worldX = (chunkX << SHIFT) + lx;
                int worldY = (chunkY << SHIFT) + ly;
                tiles[ly * SIZE + lx] = new Tile(OreMap.hasOre(worldX, worldY));
            }
        }
    }

    /** Клетка по ЛОКАЛЬНЫМ координатам внутри куска (0..31). */
    Tile tile(int localX, int localY) {
        return tiles[localY * SIZE + localX];
    }
}
