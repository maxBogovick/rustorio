package com.rustorio.model;

/**
 * Где в мире лежит руда.
 *
 * <p><b>Почему это ФУНКЦИЯ, а не массив.</b> Раньше руда раскладывалась в массив при
 * создании мира: прошлись по всем клеткам, отметили залежи. С чанками так нельзя — клетки
 * создаются по мере надобности, и «пройтись по всем» уже не получится. Значит, вопрос «есть
 * ли руда в клетке (x, y)?» должен иметь ответ БЕЗ создания мира.
 *
 * <p>Функция от координат — ровно такой ответ. Она детерминирована: одна и та же клетка
 * всегда даёт один и тот же ответ, сколько бы раз её ни спросили и в каком бы порядке ни
 * создавались куски. Без этого свойства не будет ни сохранений, ни воспроизводимых тестов.
 *
 * <p>Первые четыре залежи — те же, что были в Rust-версии (стартовая область в левом
 * верхнем углу). Остальные добавлены с появлением камеры: карта выросла, и дальние
 * залежи дают повод строить длинную логистику и вообще куда-то ехать.
 */
final class OreMap {

    /** Круглые залежи: (центр_x, центр_y, радиус). */
    private static final int[][] PATCHES = {
            {6, 5, 3}, {9, 14, 3}, {25, 6, 4}, {28, 15, 3},
            {52, 10, 4}, {74, 20, 3}, {45, 34, 4}, {14, 44, 3},
            {60, 52, 4}, {84, 42, 3}, {33, 56, 3}, {88, 8, 3},
    };

    private OreMap() {
    }

    static boolean hasOre(int x, int y) {
        for (int[] patch : PATCHES) {
            int dx = x - patch[0];
            int dy = y - patch[1];
            int r = patch[2];
            if (dx * dx + dy * dy <= r * r) {
                return true;
            }
        }
        return false;
    }
}
