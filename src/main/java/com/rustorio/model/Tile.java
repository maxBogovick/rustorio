package com.rustorio.model;

import org.jspecify.annotations.Nullable;

/**
 * Одна клетка поля: есть ли под ней руда и какое здание на ней стоит.
 *
 * <p>Простой изменяемый «контейнер данных». {@code ore} — {@code final}: залежи
 * задаются при генерации карты и не двигаются. {@code building} изменяемо: игрок
 * ставит и сносит здания. Наружу — только чтение через геттеры плюс пакетно-приватные
 * операции, которыми пользуется {@link World}.
 */
public final class Tile {

    private final boolean ore;
    private @Nullable Building building;
    /**
     * Номер тика, на котором клетку уже «застолбил» отдающий сосед.
     *
     * <p><b>Приём «штамп версии».</b> Симуляции нужно за тик отметить: «в эту клетку уже
     * кладут предмет» — иначе два соседа пропихнули бы два предмета в один слот. Наивно
     * это делается массивом отметок, который каждый тик создают заново и обнуляют. Но
     * такого массива в чанковом мире не построить (нет общего числа клеток), да и
     * обнулять миллион ячеек каждый тик — работа на ровном месте.
     *
     * <p>Вместо этого клетка помнит НОМЕР ТИКА, на котором её заняли. Занята ⇔
     * {@code claimedTick == текущий тик}. Наступил новый тик — и все прошлые отметки
     * автоматически стали «старыми». Обнуление миллиона ячеек заменилось увеличением
     * одного числа.
     */
    private int claimedTick = -1;

    Tile(boolean ore) {
        this.ore = ore;
        this.building = null;
    }

    /**
     * Попытаться застолбить клетку на этот тик.
     *
     * @return {@code true}, если удалось (клетку в этом тике ещё не занимали);
     *         {@code false}, если сосед успел раньше
     */
    boolean claim(int tick) {
        if (claimedTick == tick) {
            return false;
        }
        claimedTick = tick;
        return true;
    }

    /** Есть ли под клеткой залежь руды (бур копает только тут). */
    public boolean hasOre() {
        return ore;
    }

    /** Здание на клетке, либо {@code null}, если пусто. */
    public @Nullable Building building() {
        return building;
    }

    // Пакетно-приватно: менять здание клетки вправе только World,
    // чтобы соблюдались правила постановки/сноса из одного места.
    void setBuilding(@Nullable Building building) {
        this.building = building;
    }
}
