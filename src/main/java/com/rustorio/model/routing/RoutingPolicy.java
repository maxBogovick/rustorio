package com.rustorio.model.routing;

import com.rustorio.core.Direction;
import com.rustorio.core.Item;

/**
 * Политика маршрутизации: <b>куда сортировщик направит конкретный предмет</b>.
 *
 * <p>Это — «Стратегия» (шаблон Strategy) в чистом виде. Само здание {@link
 * com.rustorio.model.Sorter} не знает, ПО КАКОМУ правилу раскладывать предметы: оно лишь
 * держит какую-то политику и спрашивает её. Правило — отдельный маленький класс, который
 * можно понять, поменять и проверить в одиночку, не трогая здание.
 *
 * <p><b>Почему интерфейс, а не {@code if}/{@code switch} внутри здания.</b> Правил
 * маршрутизации — семейство: «всё прямо», «по типу предмета», «сначала одна лента, потом
 * другая»… Если зашить их ветками внутри {@code Sorter}, то (1) здание распухает и знает
 * сразу все правила; (2) нельзя проверить одно правило отдельно; (3) новое правило заставит
 * снова лезть в здание. Вынеся решение за интерфейс, мы получаем ровно обратное: правила
 * взаимозаменяемы, здание про них ничего не знает, а новое правило — это новый класс и НОЛЬ
 * правок в {@code Sorter}.
 *
 * <p><b>Почему этот интерфейс ОТКРЫТ, а {@link com.rustorio.model.Building} — {@code
 * sealed}.</b> Набор зданий мы держим закрытым нарочно (компилятор стережёт исчерпывающие
 * {@code switch}). А вот политик должно быть легко добавлять — в этом вся идея Стратегии.
 * Поэтому здесь обычный открытый интерфейс: реализуй и подключай.
 *
 * <p><b>Детерминизм обязателен.</b> Одинаковый предмет при одинаковых выходах обязан
 * маршрутизироваться одинаково — иначе поедут сохранения и тесты (это же стережёт {@code
 * ArchitectureTest}: никакого {@code Math.random} в домене).
 */
public interface RoutingPolicy {

    /**
     * Куда отправить {@code item}. Сортировщик заранее посчитал три своих выхода и передал их
     * готовыми — политике остаётся только ВЫБРАТЬ, не занимаясь геометрией направлений.
     *
     * @param front выход «прямо» (куда смотрит здание)
     * @param right выход направо от {@code front}
     * @param left  выход налево от {@code front}
     * @return одно из трёх направлений
     */
    Direction route(Item item, Direction front, Direction right, Direction left);

    /** Короткое имя политики — для интерфейса и (по желанию) для сохранения. */
    String name();
}
