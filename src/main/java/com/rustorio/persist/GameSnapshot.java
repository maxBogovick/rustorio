package com.rustorio.persist;

import org.jspecify.annotations.Nullable;

import java.util.List;

/**
 * Снимок всей игры в виде ПРОСТЫХ ДАННЫХ — «Memento» (снимок состояния) на границе
 * сериализации.
 *
 * <p><b>Зачем отдельный тип, а не сериализовать домен напрямую.</b> Классы домена
 * ({@code World}, {@code Furnace}, …) полны поведения, ссылок друг на друга и приватных
 * инвариантов; тащить их в JSON — значит намертво привязать формат файла к внутреннему
 * устройству игры: переименовал приватное поле — сломал все старые сохранения. DTO
 * разрывает эту связь. Это «граница»: по одну сторону — живой домен, по другую — плоские
 * записи, которые не жаль менять вместе с форматом файла.
 *
 * <p><b>{@link #version}.</b> Формат сохранений будет меняться (веха B2 добавит предметы
 * в пути). Номер схемы в файле — то, по чему загрузчик поймёт, как его читать, и сможет
 * мигрировать старые сейвы. Заводить версию ПОСЛЕ первого релиза уже поздно — поэтому она
 * здесь с самого начала.
 *
 * <p><b>Схема v2</b> добавила предметы: буферы машин и подземки — внутри {@link BuildingDto},
 * а груз лент — отдельным списком {@link #beltItems} (его восстанавливают ПОСЛЕ сборки линий).
 * Схема аддитивна: v2 — надмножество v1, и старые сейвы читаются без преобразования (см.
 * {@link BuildingDto}). <b>По-прежнему НЕ хранятся</b> аналоговые таймеры прогресса — они
 * начинаются заново, а сырьё для них лежит в буферах, так что ни один предмет не теряется.
 *
 * @param beltItems груз транспортных линий; восстанавливается после расстановки лент
 */
public record GameSnapshot(
        int version,
        int width,
        int height,
        BalanceDto balance,
        ResearchDto research,
        List<BuildingDto> buildings,
        @Nullable List<BeltItemDto> beltItems) {

    /** Текущая версия формата. Растёт при каждом изменении снимка. */
    public static final int SCHEMA_VERSION = 2;

    public GameSnapshot {
        buildings = List.copyOf(buildings);
        // v1-сейвы поля beltItems не имеют — читатель увидит null; нормализуем в пустой список.
        beltItems = beltItems == null ? List.of() : List.copyOf(beltItems);
    }
}
